-- Book Worm schema (PostgreSQL; also runs on H2 in PostgreSQL mode for tests/dev).
-- Money is NUMERIC(10,2). Timestamps are stored in UTC.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    first_name    VARCHAR(100) NOT NULL,
    last_name     VARCHAR(100) NOT NULL,
    phone         VARCHAR(20),
    gift_points   INT NOT NULL DEFAULT 0 CHECK (gift_points >= 0),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE addresses (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    first_name         VARCHAR(100) NOT NULL,
    last_name          VARCHAR(100) NOT NULL,
    email              VARCHAR(255) NOT NULL,
    phone_country_code VARCHAR(5)   NOT NULL,
    phone              VARCHAR(20)  NOT NULL,
    address_line       VARCHAR(255) NOT NULL,
    city               VARCHAR(100) NOT NULL,
    state              VARCHAR(100) NOT NULL,
    pin_code           VARCHAR(10)  NOT NULL,
    country            VARCHAR(100) NOT NULL,
    is_default         BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_addresses_user ON addresses (user_id);

CREATE TABLE categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE authors (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(150) NOT NULL,
    bio       VARCHAR(4000),
    photo_url VARCHAR(500)
);

CREATE TABLE publishers (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE books (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                 VARCHAR(255) NOT NULL,
    isbn                  VARCHAR(20) UNIQUE,
    description           VARCHAR(4000),
    author_id             BIGINT NOT NULL REFERENCES authors (id),
    publisher_id          BIGINT REFERENCES publishers (id),
    format                VARCHAR(20) NOT NULL CHECK (format IN ('PAPERBACK', 'HARDCOVER', 'EBOOK')),
    language              VARCHAR(50) NOT NULL,
    price                 NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    stock                 INT NOT NULL DEFAULT 0 CHECK (stock >= 0),
    delivery_days         INT NOT NULL DEFAULT 3 CHECK (delivery_days >= 0),
    cover_image_url       VARCHAR(500),
    back_cover_image_url  VARCHAR(500),
    published_date        DATE,
    copies_sold           INT NOT NULL DEFAULT 0,
    -- Denormalised from reviews (kept in sync by ReviewService) so that sorting by rating stays cheap.
    average_rating        NUMERIC(3, 2) NOT NULL DEFAULT 0,
    review_count          INT NOT NULL DEFAULT 0,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_books_author ON books (author_id);
CREATE INDEX idx_books_publisher ON books (publisher_id);
CREATE INDEX idx_books_published ON books (published_date);

CREATE TABLE book_categories (
    book_id     BIGINT NOT NULL REFERENCES books (id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    PRIMARY KEY (book_id, category_id)
);

CREATE TABLE carts (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE cart_items (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id  BIGINT NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    book_id  BIGINT NOT NULL REFERENCES books (id),
    quantity INT NOT NULL CHECK (quantity > 0),
    UNIQUE (cart_id, book_id)
);

CREATE TABLE wishlist_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    book_id    BIGINT NOT NULL REFERENCES books (id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (user_id, book_id)
);

CREATE TABLE followed_authors (
    user_id   BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES authors (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, author_id)
);

CREATE TABLE reviews (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    book_id    BIGINT NOT NULL REFERENCES books (id) ON DELETE CASCADE,
    rating     INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment    VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (user_id, book_id)
);
CREATE INDEX idx_reviews_book ON reviews (book_id);

CREATE TABLE coupons (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(30) NOT NULL UNIQUE,
    discount_type    VARCHAR(10) NOT NULL CHECK (discount_type IN ('PERCENT', 'FIXED')),
    discount_value   NUMERIC(10, 2) NOT NULL CHECK (discount_value > 0),
    min_order_amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
    valid_from       TIMESTAMP WITH TIME ZONE,
    valid_to         TIMESTAMP WITH TIME ZONE,
    active           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE orders (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL REFERENCES users (id),
    status             VARCHAR(20) NOT NULL
        CHECK (status IN ('PENDING_PAYMENT', 'PAID', 'CANCELLED', 'PAYMENT_FAILED')),
    -- Snapshot of the delivery address
    ship_first_name    VARCHAR(100) NOT NULL,
    ship_last_name     VARCHAR(100) NOT NULL,
    ship_email         VARCHAR(255),
    ship_phone         VARCHAR(30),
    ship_address_line  VARCHAR(255) NOT NULL,
    ship_city          VARCHAR(100) NOT NULL,
    ship_state         VARCHAR(100) NOT NULL,
    ship_pin_code      VARCHAR(10)  NOT NULL,
    ship_country       VARCHAR(100) NOT NULL,
    subtotal           NUMERIC(10, 2) NOT NULL,
    tax                NUMERIC(10, 2) NOT NULL,
    delivery_charge    NUMERIC(10, 2) NOT NULL,
    coupon_id          BIGINT REFERENCES coupons (id),
    coupon_discount    NUMERIC(10, 2) NOT NULL DEFAULT 0,
    points_redeemed    INT NOT NULL DEFAULT 0,
    points_discount    NUMERIC(10, 2) NOT NULL DEFAULT 0,
    total              NUMERIC(10, 2) NOT NULL CHECK (total >= 0),
    points_earned      INT NOT NULL DEFAULT 0,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    cancelled_at       TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_orders_user_created ON orders (user_id, created_at);

CREATE TABLE order_items (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    book_id                 BIGINT NOT NULL REFERENCES books (id),
    title                   VARCHAR(255) NOT NULL,
    author_name             VARCHAR(150),
    cover_image_url         VARCHAR(500),
    quantity                INT NOT NULL CHECK (quantity > 0),
    unit_price              NUMERIC(10, 2) NOT NULL,
    estimated_delivery_date DATE
);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_book ON order_items (book_id);

CREATE TABLE payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    method          VARCHAR(20) NOT NULL CHECK (method IN ('CREDIT_CARD', 'DEBIT_CARD', 'UPI', 'WALLET')),
    status          VARCHAR(20) NOT NULL CHECK (status IN ('SUCCESS', 'FAILED', 'REFUNDED')),
    amount          NUMERIC(10, 2) NOT NULL,
    card_last4      VARCHAR(4),
    transaction_ref VARCHAR(50) NOT NULL,
    failure_reason  VARCHAR(255),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_payments_order ON payments (order_id);

CREATE TABLE gift_point_txns (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    order_id   BIGINT REFERENCES orders (id),
    points     INT NOT NULL,
    type       VARCHAR(10) NOT NULL CHECK (type IN ('EARN', 'REDEEM', 'REFUND')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_gift_point_txns_user ON gift_point_txns (user_id, created_at);
